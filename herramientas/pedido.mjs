// Recorre la máquina de tickets: elige, imprime y "envía". node herramientas/pedido.mjs <base> <ancho> <prefijo-salida>
import { chromium } from 'playwright-core';
const [base, ancho, salida] = process.argv.slice(2);
const w = Number(ancho);
const b = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
const ctxI = await b.newContext({ viewport: { width: w, height: w < 800 ? 844 : 900 }, reducedMotion: 'no-preference' });
await ctxI.addInitScript(() => { try { sessionStorage.setItem('take-intro', '1'); } catch (e) {} });
const p = await ctxI.newPage();
const errores = [];
p.on('console', (m) => m.type() === 'error' && errores.push(m.text()));
p.on('pageerror', (e) => errores.push(e.message));
await p.goto(base.replace(/\/$/, '') + '/menu?ramen=iekei-clasico', { waitUntil: 'networkidle' });
await p.waitForTimeout(600);
await p.screenshot({ path: `${salida}-maquina.png` });
await p.getByRole('button', { name: /Agregar Gyoza/ }).click();
await p.getByRole('button', { name: /Agregar Té verde/ }).click();
await p.getByRole('radio', { name: /Firme/ }).check();
await p.selectOption('select', '13:30');
await p.fill('input[type=text]', 'Ana');
await p.getByRole('button', { name: 'Imprimir ticket' }).click();
await p.waitForTimeout(700);
const ticket = p.locator('.salida');
await ticket.scrollIntoViewIfNeeded();
await p.waitForTimeout(300);
await p.screenshot({ path: `${salida}-ticket.png` });
await p.getByRole('button', { name: /Enviar por WhatsApp/ }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${salida}-whatsapp.png` });
console.log('mensaje:\n' + (await p.locator('.burbuja-texto').textContent()));
console.log('sw', await p.evaluate(() => document.documentElement.scrollWidth), errores.length ? 'ERRORES ' + errores.join(' | ') : 'sin errores');
await b.close();
